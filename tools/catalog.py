"""Template library: CATALOG.md + a gallery page (one card per template, with the EdTech slide that uses it).

    python3 tools/catalog.py decks/edtech-full [out_dir]

Needs the deck built with --png. The gallery goes to out_dir (default /home/claude/library): index.html + img/.
"""
import sys, re, json, shutil, yaml
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent


def main(deck_dir, out=Path('/home/claude/library')):
    deck_dir = Path(deck_dir); deck = yaml.safe_load((deck_dir / 'deck.yaml').read_text())
    groups = {}
    for n, s in enumerate(deck['slides'], 1):
        groups.setdefault(s['type'], []).append((n, s))
    out.mkdir(parents=True, exist_ok=True); (out / 'img').mkdir(exist_ok=True)
    chap = {}
    rows = []
    for t, items in groups.items():
        n0, s0 = items[0]
        sec = s0.get('section') or ''
        title = re.sub(r'\s+', ' ', s0.get('title') or '').strip()
        if t.startswith('x/'):
            boxes = len(s0.get('t', {})); imgs = len(s0.get('img', []))
            kind = 'converted'; slots = f'{boxes} text boxes' + (f', {imgs} images' if imgs else '')
        else:
            kind = 'data'; slots = ', '.join(k for k in s0 if k not in ('id', 'type', 'section', 'title', 'note', 'label', 'src'))
        png = deck_dir / 'out/png' / f'{n0:03d}.png'
        if png.exists():
            Image.open(png).convert('RGB').resize((480, 336)).save(out / 'img' / f'{t.replace("/", "_")}.jpg', quality=82)
        rows.append(dict(t=t, kind=kind, slides=[n for n, _ in items], section=sec, title=title, slots=slots))
    # CATALOG.md (in the repo)
    md = ['# Template library', '',
          'One template per distinct slide (12 Nov 2026). Generated by `tools/catalog.py` from the EdTech reference deck (`decks/edtech-full`).', '',
          '- **data** templates (`templates/slides/<name>.j2`) compute their layout from the data: number of items, values, logos.',
          '- **converted** templates (`templates/slides/x/<name>.j2`) keep the PowerPoint geometry; only words and images change (`t`, `img` in deck.yaml).',
          '  To use one in a new deck, copy the EdTech slide entry from `decks/edtech-full/deck.yaml` (find it by id) and replace the words.', '',
          '| # | template | kind | EdTech slides | section | example title | slots |', '|---|---|---|---|---|---|---|']
    for i, r in enumerate(rows, 1):
        md.append(f"| {i} | `{r['t']}` | {r['kind']} | {', '.join(map(str, r['slides']))} | {r['section']} | {r['title']} | {r['slots']} |")
    (ROOT / 'CATALOG.md').write_text('\n'.join(md) + '\n')
    # gallery page
    esc = lambda s: str(s).replace('&', '&amp;').replace('<', '&lt;')
    cards = ''.join(
        f'<figure><img loading="lazy" src="img/{r["t"].replace("/", "_")}.jpg"><figcaption><b>{i}. {esc(r["t"])}</b>'
        f'<span class="k {r["kind"]}">{r["kind"]}</span><br><small>{esc(r["section"])} · slides {", ".join(map(str, r["slides"]))}</small><br>{esc(r["title"])}'
        f'<br><small>{esc(r["slots"])}</small></figcaption></figure>' for i, r in enumerate(rows, 1))
    nd = sum(r['kind'] == 'data' for r in rows)
    (out / 'index.html').write_text(f'''<!doctype html><html lang="fr"><head><meta charset="utf-8"><title>NMP · bibliothèque de modèles</title>
<style>body{{font-family:system-ui,sans-serif;background:#062A3C;color:#E8EEF0;margin:0;padding:24px}}h1{{font-weight:600;margin:0 0 6px}}p{{color:#9FB3BB;max-width:900px}}
input{{padding:8px 12px;border-radius:6px;border:1px solid #334D54;background:#0B3449;color:#fff;width:320px;margin:8px 0 18px}}
.g{{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:18px}}figure{{margin:0;background:#0B3449;border:1px solid #1C4A60;border-radius:10px;overflow:hidden}}
figure img{{width:100%;display:block}}figcaption{{padding:10px 12px;font-size:13px;line-height:1.45}}small{{color:#8FA3AB}}
.k{{float:right;font-size:11px;padding:1px 7px;border-radius:9px}}.k.data{{background:#1F6F5C}}.k.converted{{background:#334D54}}</style></head><body>
<h1>Bibliothèque de modèles · {len(rows)} modèles</h1>
<p>Un modèle par slide distincte du deck EdTech. <b>{nd} modèles « data »</b> calculent leur mise en page à partir des données ; <b>{len(rows) - nd} modèles « converted »</b> gardent la géométrie du PowerPoint et seuls les mots et logos changent. Tape un mot pour filtrer.</p>
<input id="q" placeholder="Filtrer (titre, section, nom)…" oninput="const v=this.value.toLowerCase();document.querySelectorAll('figure').forEach(f=>f.style.display=f.textContent.toLowerCase().includes(v)?'':'none')">
<div class="g">{cards}</div></body></html>''')
    print(len(rows), 'templates ->', ROOT / 'CATALOG.md', 'and', out / 'index.html')


if __name__ == '__main__':
    main(sys.argv[1], Path(sys.argv[2]) if len(sys.argv) > 2 else Path('/home/claude/library'))
