"""Text specification of every slide template (method v2, Pierre 14 Nov 2026: « tu sais déjà dans chaque bulle combien de caractères »).

    python3 tools/make_spec.py            -> specs/slides.yaml

Taken from the validated decks, not guessed. A first version measured the boxes in the browser and failed: rawfit widens
some boxes and fixlib shrinks others to their ink, so no static width gives the capacity. What every validated deck proves is
simpler: each of its texts fits its box (0 layout issues) and looks right to Pierre. So, per template and per key:
  max = the longest text seen in a validated deck (it fits)
  min = 0.85 x the median length in the deck filled to Pierre's remarks (Healthcare AI, 14 Nov 2026),
        for body texts only (median 45+ characters): a box half empty is an error too. Labels and names only have a maximum.
  caps = every text seen is in capitals
Raw templates (x/...) are keyed by box number, data templates by field path (list positions written *).
Pierre's own targets go in specs/overrides.yaml and win. Product-page twins (pp_*), cover, agenda and sources have no spec.
"""
import collections, re, statistics, sys, yaml
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from spec import leaves, plain, tpl
ROOT = Path(__file__).resolve().parent.parent
DECKS = ['healthcare-ai', 'humanoid-robotics', 'in-vivo-car-t']
FULL = 'healthcare-ai'
SKIP = {'cover', 'agenda', 'sources_list', 'key_sources', 'divider_3', 'divider_10', 'invbets'}


def main():
    M = collections.defaultdict(lambda: collections.defaultdict(list))
    for h in DECKS:
        for s in yaml.safe_load((ROOT / 'decks' / h / 'deck.yaml').read_text())['slides']:
            t = tpl(s)
            if t in SKIP or t.startswith('pp_') or str(s.get('id')).startswith('src_'): continue
            for p, v in leaves(s):
                v = plain(v)
                if not v or re.fullmatch(r'[^\w\s]{1,4}', v) or v.startswith(('../', 'media/')): continue
                M[t][p[2:] if p.startswith('t.') else p].append((h, v))
    spec = {}
    for t, K in sorted(M.items()):
        for k, obs in K.items():
            L = [len(v) for _, v in obs]; e = {'max': max(L)}
            ref = [len(v) for h, v in obs if h == FULL] or L
            if statistics.median(L) >= 45: e['min'] = int(0.85 * statistics.median(ref))
            else: e['max'] = int(max(L) * 1.25) + 2       # a label or a name: seen in few decks, so room for a longer one (names are never cut)
            if all(v == v.upper() and re.search('[A-Z]', v) for _, v in obs): e['caps'] = True
            spec.setdefault(t, {})[k] = e
    ov = ROOT / 'specs/overrides.yaml'
    for t, K in ((yaml.safe_load(ov.read_text()) or {}) if ov.exists() else {}).items():
        for k, e in (K or {}).items(): spec.setdefault(t, {}).setdefault(str(k), {}).update(e)
    (ROOT / 'specs').mkdir(exist_ok=True)
    (ROOT / 'specs/slides.yaml').write_text('# generated by tools/make_spec.py from ' + ', '.join(DECKS) + ' + specs/overrides.yaml. Do not edit: edit overrides.yaml\n'
                                            + yaml.dump(spec, allow_unicode=True, sort_keys=True, width=200))
    print(len(spec), 'templates,', sum(len(v) for v in spec.values()), 'text keys -> specs/slides.yaml')


if __name__ == '__main__':
    main()
